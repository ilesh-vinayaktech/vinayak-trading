# ruff: noqa: E501
"""Review pack for the delivery cost schedules (readiness K1): one table per period with every component's rate, the source it cites and the quote, the
assumptions, and a check that the periods leave no gap and no overlap. Read-only. usage: cost_schedule_review.py [--out docs/stage4/cost/COST_REVIEW.md]"""

import argparse
import json
from datetime import date, timedelta
from pathlib import Path

ap = argparse.ArgumentParser()
ap.add_argument("--dir", type=Path, default=Path("config/cost_schedules"))
ap.add_argument("--out", type=Path, default=Path("docs/stage4/cost/COST_REVIEW.md"))
ap.add_argument("--window-from", default="2020-10-01")
a = ap.parse_args()
sch = sorted(
    (
        s
        for f in sorted(a.dir.glob("*.json"))
        for s in json.loads(f.read_text())["schedules"]
        if s["product"] == "DELIVERY"
    ),
    key=lambda s: s["valid_from"],
)
lines = ["# Delivery cost schedules: what must be checked before VERIFIED (readiness K1)", "",
         "Generated by `scripts/cost_schedule_review.py` from `config/cost_schedules/`. Every schedule below is `extracted_unverified`: a person must confirm each quote against its document.",
         "A schedule is only usable for promotion once VERIFIED; the assumed-backfill intraday schedule never is.", ""]  # fmt: skip
gaps = []
prev_end: date | None = None
for s in sch:
    start = date.fromisoformat(s["valid_from"])
    if prev_end is not None and start != prev_end + timedelta(days=1):
        gaps.append(f"{prev_end} -> {start}")
    prev_end = date.fromisoformat(s["valid_until"]) if s["valid_until"] else None
lines += ["## Coverage", f"{len(sch)} delivery periods, {sch[0]['valid_from']} to {sch[-1]['valid_until'] or 'open'}. Gaps or overlaps between consecutive periods: {', '.join(gaps) or 'none'}.",
          f"The research window starts {a.window_from}: periods ending before it are not needed for a strict run.", ""]  # fmt: skip
for s in sch:
    needed = (s["valid_until"] is None) or s["valid_until"] >= a.window_from
    lines += [f"## {s['valid_from']} to {s['valid_until'] or 'open'} ({s['id']}, v{s['version']}){'' if needed else '  [before the research window]'}", "",
              "| Component | Side | Rate or amount | In GST base | Source key | Quote from the source | Where |", "|---|---|---|---|---|---|---|"]  # fmt: skip
    for c in s["components"]:
        if (
            c["basis"] == "GST_BASE"
        ):  # a rule, not a percentage of value: it applies to the components flagged below
            rate = f"{c['rate_pct']}% of the GST base (sum of components marked yes)"
        elif "rate_pct" in c:
            rate = f"{c['rate_pct']}% of value"
        else:
            rate = f"Rs {c['amount']} per scrip" + (
                " (GST included)" if c.get("gst_inclusive") else ""
            )
        src = s["sources"].get(c["source"], {})
        quote = (src.get("quote") or "no quote on record").replace("|", "/")
        lines.append(
            f"| {c['type']} | {c['side']} | {rate} | {'yes' if c.get('taxable_for_gst') else ''} | `{c['source']}` | {quote[:170]} | {src.get('locator', '')[:110].replace('|', '/')} ({src.get('url', 'no url')}) |"
        )
    if s.get("assumptions"):
        lines += ["", "Assumptions (not evidenced):", *[f"- {x}" for x in s["assumptions"]]]
    lines += [""]
a.out.parent.mkdir(parents=True, exist_ok=True)
a.out.write_text("\n".join(lines))
need = [s for s in sch if s["valid_until"] is None or s["valid_until"] >= a.window_from]
print(
    f"{len(sch)} periods ({len(need)} inside the research window), gaps: {gaps or 'none'}, with assumptions: {[s['valid_from'] for s in need if s.get('assumptions')]}"
)
